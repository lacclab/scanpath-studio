"""UX-137: what the 🗂️ Data page says about the open dataset, and how loudly.

The page opened with a full **ℹ️ About the `<name>` dataset** section — a second
subheader, the description, the corpus home link, a coordinate-provenance
sentence and a six-row published-vs-loaded table — all standing above the counts
that are the reason to visit. One sentence stays; the rest moved behind a ❔.

The per-metric spread went the same way: a four-column table where Mean, Std,
Min and Max carried equal weight became three `st.metric`s matching the headline
counts directly above them, with the spread on each metric's own hover.
"""

from __future__ import annotations

import pandas as pd
import pytest

from tests.conftest import APP_SCRIPT, pin_data_view

streamlit_testing = pytest.importorskip("streamlit.testing.v1")
AppTest = streamlit_testing.AppTest


class TestTheOverviewSentence:
    @staticmethod
    def _split(text):
        from scanpath_studio.app import _overview_sentence

        return _overview_sentence(text)

    def test_the_first_sentence_is_the_overview(self):
        head, rest = self._split(
            "A packaged subset of OneStop. Regenerated by hand. And again."
        )
        assert head == "A packaged subset of OneStop."
        assert rest == "Regenerated by hand. And again."

    def test_a_dot_inside_a_code_span_is_not_a_boundary(self):
        """Several descriptions end on a module path; cutting one at its first
        dot reads as a typo rather than as a summary."""
        head, rest = self._split(
            "A packaged subset, so the app opens with something real. "
            "Regenerated by `python -m scanpath_studio.update_sample_data`."
        )
        assert head == "A packaged subset, so the app opens with something real."
        assert "update_sample_data" in rest

    def test_a_single_sentence_has_no_remainder(self):
        head, rest = self._split("Potsdam Textbook Corpus — German reading.")
        assert head == "Potsdam Textbook Corpus — German reading."
        assert rest == ""

    def test_a_lowercase_continuation_is_not_a_boundary(self):
        """`v1.2` and friends: a dot followed by lowercase is inside a token."""
        head, rest = self._split("Prepared with tooling v1.2 and shipped.")
        assert head == "Prepared with tooling v1.2 and shipped."
        assert rest == ""

    @pytest.mark.parametrize("text", ["", None, "   "])
    def test_nothing_in_nothing_out(self, text):
        assert self._split(text) == ("", "")


class TestThePage:
    @staticmethod
    def _data_page():
        at = AppTest.from_file(APP_SCRIPT, default_timeout=600)
        pin_data_view(at)
        at.run()
        assert not at.exception, at.exception
        return at

    def test_the_about_heading_is_gone(self):
        at = self._data_page()
        headings = [s.value for s in at.subheader]
        assert not any(h.startswith("ℹ️ About") for h in headings), headings
        assert any("What's in the" in h for h in headings), headings

    def test_the_overview_is_one_sentence_under_the_heading(self):
        at = self._data_page()
        captions = [c.value for c in at.caption]
        overview = [c for c in captions if "packaged subset" in c]
        assert overview, captions[:8]
        assert overview[0].count(".") == 1, overview[0]

    def test_the_technicalities_render_once_each(self):
        """The ❔ body is rendered twice — once into a throwaway container to
        find out whether it has anything to say — so the discarded copy must
        actually be discarded."""
        at = self._data_page()
        mds = [str(m.value) for m in at.markdown]
        assert sum("Where the coordinates come from" in m for m in mds) == 1
        assert sum("Published figures." in m for m in mds) == 1
        assert sum("corpus' own home page" in m for m in mds) == 1


class TestTheSpreadMetrics:
    @staticmethod
    def _spread(**overrides):
        row = {
            "Metric": "Fixations per trial",
            "Mean": 133.71,
            "Std": 69.57,
            "Min": 35,
            "Max": 311,
        }
        row.update(overrides)
        return row

    def test_a_count_mean_is_rounded(self):
        from scanpath_studio.tabs import _format_spread_mean

        assert _format_spread_mean(133.71) == "134"
        assert _format_spread_mean(108.94) == "109"
        assert _format_spread_mean(12.0) == "12"

    def test_a_small_mean_keeps_a_decimal(self):
        """0.4 rounded to 0 reads as "none", which is a different claim."""
        from scanpath_studio.tabs import _format_spread_mean

        assert _format_spread_mean(0.4) == "0.4"

    def test_a_missing_mean_is_a_dash_not_nan(self):
        from scanpath_studio.tabs import _format_spread_mean

        assert _format_spread_mean(float("nan")) == "—"
        assert _format_spread_mean(None) == "—"

    def test_the_spread_moves_to_the_hover(self):
        from scanpath_studio.tabs import _spread_help

        help_text = _spread_help(self._spread())
        assert "± 69.57 std" in help_text
        assert "range 35–311" in help_text
        assert "Computed after the current filters." in help_text

    def test_a_constant_metric_says_so_rather_than_printing_zeros(self):
        from scanpath_studio.tabs import _spread_help

        help_text = _spread_help(
            self._spread(
                Metric="Trials per participant", Mean=12, Std=0, Min=12, Max=12
            )
        )
        assert "The same for every row" in help_text
        assert "±" not in help_text

    def test_they_are_metrics_beside_the_counts_not_a_table(self):
        at = TestThePage._data_page()
        labels = [m.label for m in at.metric]
        for expected in (
            "Trials per participant",
            "Fixations per trial",
            "Words per trial",
        ):
            assert expected in labels, labels
        # Rounded on the user's call — these count things.
        by_label = {m.label: m.value for m in at.metric}
        assert "." not in by_label["Fixations per trial"]
        assert "." not in by_label["Words per trial"]

    def test_an_empty_spread_draws_nothing(self):
        from scanpath_studio import tabs

        tabs._render_spread_cards(pd.DataFrame())
        tabs._render_spread_cards(None)
